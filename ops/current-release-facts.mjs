/** Current documentation facts only; reads source contracts, never a deployed host. */
import { existsSync, readFileSync, readdirSync, writeFileSync, realpathSync } from 'node:fs';
import { resolve, relative, dirname, extname } from 'node:path';
import { fileURLToPath } from 'node:url';
const requireFact = (value, reason) => { if (!value) throw Error(reason); };
const json = (root, path) => JSON.parse(readFileSync(resolve(root, path), 'utf8'));
const text = (root, path) => readFileSync(resolve(root, path), 'utf8');
const sorted = values => [...values].sort();
const same = (a, b) => JSON.stringify(sorted(a)) === JSON.stringify(sorted(b));
export function catalogMapIds(root) {
  const source = text(root, 'src/world/catalog.ts');
  const match = source.match(/export const WORLD_CATALOG\s*=\s*(\{[\s\S]*?\})\s+as const/);
  requireFact(match, 'Catalog must retain its explicit JSON object contract');
  const ids = Object.keys(JSON.parse(match[1]));
  requireFact(ids.length > 0 && ids.every(id => /^[a-z][a-z0-9-]*$/.test(id)), 'Invalid current catalog map identities');
  return ids.sort();
}
export function currentFacts(root) {
  const ids = catalogMapIds(root);
  const maps = readdirSync(resolve(root, 'maps'));
  const native = suffix => maps.filter(p => p.endsWith(suffix)).map(p => p.slice(0, -suffix.length));
  const manifest = json(root, 'publication/source-manifest.json');
  requireFact(ids.length > 0 && same(ids, native('.tmj')) && same(ids, native('.wam')) && manifest.maps === ids.length && manifest.wams === ids.length, 'Catalog/native map pairs/publication counts disagree');
  requireFact(manifest.extensionInventory && typeof manifest.extensionInventory === 'object' && !Array.isArray(manifest.extensionInventory), 'Missing reviewed extension inventory');
  const nodes = new Set(text(root, '.nvmrc').split('\n').map(line => line.trim()).filter(Boolean));
  requireFact(nodes.size === 1 && /^\d+\.\d+\.\d+$/.test([...nodes][0]), 'Canonical Node pin (.nvmrc) missing, malformed or ambiguous');
  const tiled = new Set([...text(root, 'tools/maps/render.ts').matchAll(/tiled-(\d+\.\d+\.\d+)/g)].map(m => m[1]));
  requireFact(tiled.size === 1, 'Canonical native Tiled pin (tools/maps/render.ts) missing or ambiguous');
  const upstream = json(root, 'ops/images.lock.json').workadventureSource;
  requireFact(typeof upstream === 'string' && /^[a-f0-9]{40}$/.test(upstream) && json(root, 'ops/play-cookie/provenance.json').baselineSourceCommit === upstream, 'WorkAdventure source/provenance pins disagree');
  const lock = json(root, 'package-lock.json');
  const tools = Object.fromEntries(['vite', 'typescript', 'vitest', 'tsx', 'zod', 'sharp'].map(name => {
    const version = lock.packages?.['node_modules/' + name]?.version;
    requireFact(typeof version === 'string' && /^\d+\.\d+\.\d+(?:[-+].*)?$/.test(version), 'Missing locked tool: ' + name);
    return [name, version];
  }));
  return { mapPairs: ids.length, extensionCount: Object.keys(manifest.extensionInventory).length, nodeVersion: [...nodes][0], tiledVersion: [...tiled][0], workAdventureSource: upstream, tools };
}
export function renderFacts(facts) {
  return `# Current release facts\n\nGenerated by [the documentation contract checker](../ops/current-release-facts.mjs). Run \`node ops/current-release-facts.mjs --write\` after reviewed source-contract changes, then \`node ops/current-release-facts.mjs --check\`. Do not edit this table by hand.\n\n| Fact | Source-derived value | Owner |\n| --- | --- | --- |\n| Native catalog TMJ/WAM pairs | ${facts.mapPairs} | [Catalog](../src/world/catalog.ts), native maps and [publication manifest](../publication/source-manifest.json) |\n| Reviewed extension entries | ${facts.extensionCount} | [Publication manifest](../publication/source-manifest.json) |\n| Canonical Node.js | ${facts.nodeVersion} | [Node version file](../.nvmrc) |\n| Canonical native Tiled | ${facts.tiledVersion} | [Native renderer](../tools/maps/render.ts) |\n| WorkAdventure source revision | \`${facts.workAdventureSource}\` | [Image lock](../ops/images.lock.json), [overlay provenance](../ops/play-cookie/provenance.json) |\n${Object.entries(facts.tools).map(([name, version]) => `| Locked root ${name} | ${version} | [Package lock](../package-lock.json) |`).join('\n')}\n\nThese are checked-in source facts, not a fresh security audit or deployed-version receipt. They do not establish live map, hosting, restore or event acceptance. Dated historical records retain their original versions and counts. See [verification boundaries](operating/venue-guide.md).\n`;
}
function anchors(markdown) {
  const result = new Set(); const counts = new Map();
  for (const line of markdown.split('\n')) {
    const heading = line.match(/^#{1,6}\s+(.+?)\s*#*$/);
    if (heading) {
      const base = heading[1].toLowerCase().replace(/<[^>]*>/g, '').replace(/[^\p{L}\p{N}_\s-]/gu, '').replace(/\s/g, '-');
      const n = counts.get(base) ?? 0; counts.set(base, n + 1); result.add(base + (n ? '-' + n : ''));
    }
    for (const match of line.matchAll(/\b(?:id|name)=["']([^"']+)["']/g)) result.add(match[1]);
  }
  return result;
}
export function localLinks(root, file, markdown) {
  const errors = [];
  const active = markdown.replace(/^(?:```|~~~)[\s\S]*?^(?:```|~~~)[^\n]*$/gm, '').replace(/`[^`\n]*`/g, '');
  const references = new Map([...active.matchAll(/^ {0,3}\[([^\]]+)\]:\s*(<[^>]+>|[^\s]+)/gm)].map(m => [m[1].toLowerCase().trim().replace(/\s+/g, ' '), m[2]]));
  const targets = [];
  for (const match of active.matchAll(/!?\[([^\]]+)\]\[([^\]]*)\]/g)) {
    const key = (match[2] || match[1]).toLowerCase().trim().replace(/\s+/g, ' ');
    if (!references.has(key)) errors.push(`${file}: missing local reference ${key}`); else targets.push(references.get(key));
  }
  targets.push(...[...active.matchAll(/!?\[[^\]]*\]\((<[^>]+>|[^\s)]+)(?:\s+["'][^)]*)?\)/g)].map(m => m[1]));
  for (const raw of targets) {
    const href = raw.replace(/^<|>$/g, '');
    if (/^[a-z][a-z\d+.-]*:/i.test(href) || href.startsWith('//')) continue;
    try {
      const [pathQuery, fragment] = href.split('#'); const path = decodeURIComponent(pathQuery.split('?')[0]);
      const target = resolve(dirname(resolve(root, file)), path || file.split('/').at(-1));
      const within = relative(resolve(root), target);
      if (within.startsWith('..') || !existsSync(target) || relative(realpathSync(root), realpathSync(target)).startsWith('..')) { errors.push(`${file}: missing/escaping local link ${href}`); continue; }
      if (fragment && extname(target) === '.md' && !anchors(readFileSync(target, 'utf8')).has(decodeURIComponent(fragment))) errors.push(`${file}: missing local anchor ${href}`);
    } catch { errors.push(`${file}: invalid local link ${href}`); }
  }
  return errors;
}
export function checkCurrentDocs(root) {
  const errors = []; const expected = renderFacts(currentFacts(root));
  if (!existsSync(resolve(root, 'docs/current-release-facts.md')) || text(root, 'docs/current-release-facts.md') !== expected) errors.push('Stale/missing generated facts: run node ops/current-release-facts.mjs --write');
  const paths = ['README.md', 'docs/current-release-facts.md', 'docs/dependencies.md', 'docs/varcamp-map-handoff.md'];
  if (existsSync(resolve(root, 'docs/operating'))) paths.push(...readdirSync(resolve(root, 'docs/operating')).filter(p => p.endsWith('.md')).map(p => 'docs/operating/' + p));
  for (const path of paths) {
    if (!existsSync(resolve(root, path))) { errors.push('Missing active documentation: ' + path); continue; }
    let content = text(root, path);
    if (path === 'docs/dependencies.md') content = content.split(/^## /m)[0] + '\n' + (content.split('## Current tools and release')[1] ?? '');
    errors.push(...localLinks(root, path, content));
  }
  return errors;
}
if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
  requireFact(process.argv.length === 3 && ['--write', '--check'].includes(process.argv[2]), 'Use --write or --check');
  if (process.argv[2] === '--write') writeFileSync(resolve(root, 'docs/current-release-facts.md'), renderFacts(currentFacts(root)));
  else { const errors = checkCurrentDocs(root); if (errors.length) { console.error(errors.join('\n')); process.exitCode = 1; } else console.log('Current release facts and active local links verified'); }
}
